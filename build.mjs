#!/usr/bin/env node
// Static site build for the Selo marketing site. No framework, no client-side rendering:
// every page is plain HTML generated at build time, so feature flags remove content entirely.
//
//   node build.mjs                         production build (clean URLs) into dist/
//   LINK_MODE=files node build.mjs         preview build (relative index.html links)
//   SITE_FEATURES_ALL=true node build.mjs  preview every upcoming feature (never deploy this)
//   SITE_FEATURES_VOICE_NOTES=true ...     switch one feature on
import { mkdirSync, writeFileSync, readFileSync, copyFileSync, rmSync, existsSync } from 'node:fs';
import { join, dirname } from 'node:path';
import { ROOT, config, brand, company, flags, setRoute, href, asset, absUrl, esc, t, LINK_MODE } from './src/lib/core.mjs';
import { header, footer, ctaBand, cookieBanner } from './src/lib/components.mjs';
import { tokensCss } from './src/styles/tokens.mjs';
import home from './src/content/en/home.mjs';
import features from './src/content/en/features.mjs';
import pricing from './src/content/en/pricing.mjs';
import companyPages from './src/content/en/company.mjs';
import legal from './src/content/en/legal.mjs';
import { featureRows } from './src/content/en/pricing.mjs';

const OUT = join(ROOT, process.env.OUT_DIR || 'dist');
rmSync(OUT, { recursive: true, force: true });
mkdirSync(OUT, { recursive: true });

const allPages = () => [home(), ...features(), pricing(), ...companyPages(), ...legal()];
const fileFor = (route) => (route === '/' ? 'index.html' : route === '/404' ? '404.html' : `${route.slice(1)}/index.html`);
const write = (rel, content) => { const p = join(OUT, rel); mkdirSync(dirname(p), { recursive: true }); writeFileSync(p, content); };

// ---------- Validate copy limits ----------
setRoute('/');
const routes = allPages().map((p) => p.route);
const problems = [];
for (const p of allPages()) {
  if (p.title.length > 60) problems.push(`title > 60 chars (${p.title.length}): ${p.route} "${p.title}"`);
  if (p.description.length > 155) problems.push(`description > 155 chars (${p.description.length}): ${p.route}`);
}
if (new Set(routes).size !== routes.length) problems.push('Duplicate routes');

// ---------- Assets ----------
const fontFiles = new Set();
const fontCss = [400, 500, 600, 700].map((w) => readFileSync(join(ROOT, `node_modules/@fontsource/inter/${w}.css`), 'utf8')
  .replace(/, url\(\.\/files\/[^)]+\.woff\) format\('woff'\)/g, '')
  .replace(/url\(\.\/files\/([^)]+)\)/g, (_, f) => { fontFiles.add(f); return `url(fonts/${f})`; })).join('\n');
mkdirSync(join(OUT, 'assets/fonts'), { recursive: true });
for (const f of fontFiles) copyFileSync(join(ROOT, 'node_modules/@fontsource/inter/files', f), join(OUT, 'assets/fonts', f));
write('assets/styles.css', `/* Generated by build.mjs: fonts + tokens + styles */\n${fontCss}\n${tokensCss()}\n${readFileSync(join(ROOT, 'src/styles/styles.css'), 'utf8')}`);
write('assets/main.js', readFileSync(join(ROOT, 'src/assets/main.js'), 'utf8'));
mkdirSync(join(OUT, 'assets/brand'), { recursive: true });
for (const f of ['selo-mark.svg', 'logo-original.jpg']) copyFileSync(join(ROOT, 'src/assets/brand', f), join(OUT, 'assets/brand', f));

let Resvg = null;
try { ({ Resvg } = await import('@resvg/resvg-js')); } catch { console.warn('resvg not installed: skipping PNG icons and Open Graph images'); }
const markSvg = readFileSync(join(ROOT, 'src/assets/brand/selo-mark.svg'), 'utf8');
const png = (svg, width) => new Resvg(svg, { fitTo: { mode: 'width', value: width }, font: { loadSystemFonts: true, defaultFontFamily: 'Inter' } }).render().asPng();
if (Resvg) {
  write('apple-touch-icon.png', png(markSvg, 180));
  write('favicon-32.png', png(markSvg, 32));
  write('assets/brand/selo-mark-512.png', png(markSvg, 512));
}
write('favicon.svg', markSvg);

// ---------- Open Graph images (1200x630: brand background, page H1, phone shape) ----------
function wrapLines(text, max) {
  const words = text.split(' '); const lines = []; let line = '';
  for (const w of words) { if ((line + ' ' + w).trim().length > max) { lines.push(line.trim()); line = w; } else line += ' ' + w; }
  if (line.trim()) lines.push(line.trim());
  return lines.slice(0, 4);
}
function ogSvg(title) {
  const xmlEsc = (s) => s.replace(/&/g, '&amp;').replace(/</g, '&lt;');
  const lines = wrapLines(title, 20);
  const mark = markSvg.replace('<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 100 100" role="img" aria-label="Selo">', '<svg x="72" y="64" width="64" height="64" viewBox="0 0 100 100">');
  return `<svg xmlns="http://www.w3.org/2000/svg" width="1200" height="630" viewBox="0 0 1200 630">
  <rect width="1200" height="630" fill="#066332"/>
  <circle cx="1120" cy="-40" r="300" fill="none" stroke="#fff" stroke-opacity=".07" stroke-width="80"/>
  ${mark}
  <text x="152" y="108" font-family="Inter" font-weight="700" font-size="40" fill="#fff">${esc(brand.name)}</text>
  ${lines.map((l, i) => `<text x="72" y="${236 + i * 72}" font-family="Inter" font-weight="700" font-size="60" fill="#fff">${xmlEsc(l)}</text>`).join('')}
  <text x="72" y="566" font-family="Inter" font-weight="500" font-size="28" fill="#DDF6E7">WhatsApp for Shopify · selo.example</text>
  <g transform="translate(860 150)">
    <rect width="260" height="520" rx="40" fill="#0F172A"/>
    <rect x="12" y="12" width="236" height="496" rx="30" fill="#EEF4EF"/>
    <rect x="12" y="12" width="236" height="64" rx="0" fill="#fff"/>
    <rect x="30" y="110" width="170" height="70" rx="14" fill="#DCFCE7"/>
    <rect x="70" y="200" width="140" height="44" rx="14" fill="#fff"/>
    <rect x="30" y="264" width="180" height="84" rx="14" fill="#DCFCE7"/>
  </g>
</svg>`;
}

// ---------- Structured data ----------
const org = () => ({
  '@type': 'Organization', '@id': `${company.website}/#organization`, name: brand.name, legalName: company.legalName, url: `${company.website}/`,
  logo: `${company.website}/assets/brand/selo-mark-512.png`, email: company.emails.general,
  sameAs: Object.values(company.social),
  address: { '@type': 'PostalAddress', streetAddress: company.address.street, addressLocality: company.address.city, addressRegion: company.address.region, postalCode: company.address.postalCode, addressCountry: company.address.countryCode },
  contactPoint: [
    { '@type': 'ContactPoint', contactType: 'sales', email: company.emails.sales, telephone: company.phones.sales.replace(/[^+\d]/g, ''), availableLanguage: ['English'] },
    { '@type': 'ContactPoint', contactType: 'customer support', email: company.emails.support, telephone: company.phones.support.replace(/[^+\d]/g, ''), availableLanguage: ['English'] },
  ],
});
const softwareApp = () => ({
  '@type': 'SoftwareApplication', name: brand.productName, applicationCategory: 'BusinessApplication', operatingSystem: 'Web',
  description: brand.description, url: `${company.website}/`, publisher: { '@id': `${company.website}/#organization` },
  offers: config.pricing.plans.map((p) => ({ '@type': 'Offer', name: p.name, price: String(p.monthly), priceCurrency: config.pricing.currency, url: absUrl('/pricing') })),
});
const plain = (html) => html.replace(/<[^>]+>/g, '').replace(/\s+/g, ' ').trim();

function jsonLd(page) {
  const graph = [org()];
  if (page.softwareApp) graph.push(softwareApp());
  if (page.faqSchema) graph.push({ '@type': 'FAQPage', mainEntity: page.faqSchema.map((f) => ({ '@type': 'Question', name: plain(f.q), acceptedAnswer: { '@type': 'Answer', text: plain(f.a) } })) });
  if (page.trail) graph.push({ '@type': 'BreadcrumbList', itemListElement: [['Home', '/'], ...page.trail].map(([n, r], i) => ({ '@type': 'ListItem', position: i + 1, name: plain(n), item: absUrl(r) })) });
  if (page.howTo) graph.push({ '@type': 'HowTo', name: 'Set up Selo for WhatsApp', step: page.howTo.map((s, i) => ({ '@type': 'HowToStep', position: i + 1, name: s.name, text: s.text })) });
  if (page.blogPost) graph.push({ '@type': 'BlogPosting', headline: page.blogPost.title, datePublished: page.blogPost.date, description: page.blogPost.excerpt, author: { '@id': `${company.website}/#organization` }, publisher: { '@id': `${company.website}/#organization` }, mainEntityOfPage: absUrl(page.route) });
  return JSON.stringify({ '@context': 'https://schema.org', '@graph': graph }).replace(/</g, '\\u003c');
}

// ---------- Page shell ----------
function render(page) {
  const canonical = page.route === '/404' ? null : absUrl(page.route);
  const ogTitle = page.ogTitle || page.title;
  const ogImg = `${company.website}/og/${page.route === '/' ? 'home' : page.route.slice(1).replace(/\//g, '-')}.png`;
  const clientCfg = { route: page.route, analytics: config.analytics, ...(page.extraScriptVars || {}) };
  const body = page.body.replace(/__MARK__/g, asset('assets/brand/selo-mark.svg'));
  return `<!DOCTYPE html>
<html lang="${t('lang')}" dir="ltr">
<head>
<meta charset="utf-8">
<meta name="viewport" content="width=device-width, initial-scale=1">
<title>${esc(page.title)}</title>
<meta name="description" content="${esc(page.description)}">
${page.noindex ? '<meta name="robots" content="noindex, follow">' : ''}
${canonical ? `<link rel="canonical" href="${canonical}">\n<link rel="alternate" hreflang="en" href="${canonical}">\n<link rel="alternate" hreflang="x-default" href="${canonical}">` : ''}
<meta name="theme-color" content="#087A3F" media="(prefers-color-scheme: light)">
<meta name="theme-color" content="#0B1220" media="(prefers-color-scheme: dark)">
<meta property="og:type" content="website">
<meta property="og:site_name" content="${esc(brand.name)}">
<meta property="og:title" content="${esc(ogTitle)}">
<meta property="og:description" content="${esc(page.description)}">
${canonical ? `<meta property="og:url" content="${canonical}">` : ''}
${page.noindex ? '' : `<meta property="og:image" content="${ogImg}">\n<meta property="og:image:width" content="1200">\n<meta property="og:image:height" content="630">\n<meta name="twitter:image" content="${ogImg}">`}
<meta name="twitter:card" content="summary_large_image">
<meta name="twitter:title" content="${esc(ogTitle)}">
<meta name="twitter:description" content="${esc(page.description)}">
<link rel="icon" href="${asset('favicon.svg')}" type="image/svg+xml">
<link rel="icon" href="${asset('favicon-32.png')}" sizes="32x32" type="image/png">
<link rel="apple-touch-icon" href="${asset('apple-touch-icon.png')}">
<link rel="preload" href="${asset('assets/fonts/inter-latin-400-normal.woff2')}" as="font" type="font/woff2" crossorigin>
<link rel="preload" href="${asset('assets/fonts/inter-latin-700-normal.woff2')}" as="font" type="font/woff2" crossorigin>
<link rel="stylesheet" href="${asset('assets/styles.css')}">
<script>(function(){var r=document.documentElement;r.className+=' js';try{var t=JSON.parse(localStorage.getItem('selo-theme'));if(t==='light'||t==='dark')r.setAttribute('data-theme',t)}catch(e){}})();</script>
<script type="application/ld+json">${jsonLd(page)}</script>
${page.turnstile ? '<script src="https://challenges.cloudflare.com/turnstile/v0/api.js" async defer></script>' : ''}
</head>
<body>
<a class="skip-link" href="#main">${t('skip')}</a>
${header()}
<main id="main" tabindex="-1">
${body}
${page.noCta ? '' : ctaBand()}
</main>
${footer()}
${cookieBanner()}
<script>window.SELO=${JSON.stringify(clientCfg).replace(/</g, '\\u003c')};</script>
<script src="${asset('assets/main.js')}" defer></script>
</body>
</html>
`;
}

// ---------- Render every route (content is regenerated per route so relative links are correct) ----------
const built = [];
for (const route of routes) {
  setRoute(route);
  const page = allPages().find((p) => p.route === route);
  write(fileFor(route), render(page).replace(/\n{3,}/g, '\n\n'));
  built.push(page);
  if (Resvg && !page.noindex) write(`og/${route === '/' ? 'home' : route.slice(1).replace(/\//g, '-')}.png`, png(ogSvg(plain(page.ogTitle || page.body.match(/<h1[^>]*>([\s\S]*?)<\/h1>/)?.[1] || page.title)), 1200));
}

// ---------- sitemap.xml + robots.txt ----------
const today = new Date().toISOString().slice(0, 10);
const indexable = built.filter((p) => !p.noindex);
write('sitemap.xml', `<?xml version="1.0" encoding="UTF-8"?>
<urlset xmlns="http://www.sitemaps.org/schemas/sitemap/0.9" xmlns:xhtml="http://www.w3.org/1999/xhtml">
${indexable.map((p) => `  <url><loc>${absUrl(p.route)}</loc><xhtml:link rel="alternate" hreflang="en" href="${absUrl(p.route)}"/><lastmod>${today}</lastmod><priority>${(p.priority ?? 0.5).toFixed(1)}</priority></url>`).join('\n')}
</urlset>
`);
write('robots.txt', `User-agent: *\nAllow: /\nDisallow: /404.html\n\nSitemap: ${company.website}/sitemap.xml\n`);

// ---------- Report ----------
const on = Object.entries(flags).filter(([, v]) => v).map(([k]) => k);
console.log(`Built ${built.length} pages into ${OUT} (links: ${LINK_MODE})`);
console.log(`Feature flags on: ${on.length ? on.join(', ') : 'none (launch state)'}`);
console.log(`Pricing rows: ${featureRows().length}`);
if (problems.length) { console.warn('\nCopy checks:\n- ' + problems.join('\n- ')); if (process.env.STRICT) process.exit(1); }
